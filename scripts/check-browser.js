// 用 Playwright CLI 的 run-code --filename 执行；不参与应用构建。
async (page) => {
  const checks = []
  const errors = []
  page.on('pageerror', error => errors.push(error.message))
  page.on('console', message => { if (message.type() === 'error') errors.push(message.text()) })
  const assert = (condition, message) => { if (!condition) throw new Error(message); checks.push(message) }
  const visible = async (locator, message) => { await locator.waitFor({ state: 'visible', timeout: 12000 }); checks.push(message) }
  const go = async path => { await page.goto(`http://127.0.0.1:5173/#${path}`); await page.locator('main h1').waitFor() }
  const openScenario = async () => { await page.getByRole('button', { name: '演示场景' }).click(); await page.getByRole('dialog').waitFor() }
  const closeScenario = async () => page.getByRole('button', { name: '应用并查看' }).click()
  const saved = async () => page.evaluate(() => JSON.parse(localStorage.getItem('devops-demo-v1')).records)
  await page.setViewportSize({ width: 1440, height: 1000 })
  await go('/pipelines/2841')
  await openScenario()
  await page.getByRole('button', { name: '恢复默认数据' }).click()
  await closeScenario()
  await visible(page.getByRole('heading', { name: '检查通过，可以部署预发' }), '默认流水线显示检查结果与部署入口')
  await page.getByRole('button', { name: '查看日志', exact: true }).first().click()
  await visible(page.getByRole('dialog'), '阶段日志可打开')
  await page.keyboard.press('Escape')
  assert(await page.getByRole('dialog').count() === 0, 'Escape 关闭原生对话框')
  assert(await page.evaluate(() => document.activeElement?.textContent?.includes('查看日志')), '对话框关闭后焦点返回触发按钮')
  await page.locator('.skip-link').focus()
  await page.keyboard.press('Enter')
  assert(page.url().includes('/pipelines/2841') && await page.evaluate(() => document.activeElement.id === 'main-content'), '跳转主内容不会破坏 Hash 路由')
  await page.getByRole('link', { name: '部署到预发', exact: true }).click()
  await page.locator('#deploy-note').fill('预发验收：验证订单分页与响应时间')
  await openScenario()
  await page.locator('#request-failure').check()
  await closeScenario()
  await page.getByRole('button', { name: '确认并发起部署' }).click()
  await visible(page.getByRole('alert').filter({ hasText: '部署请求未能提交' }), '模拟请求失败提供明确反馈')
  assert(await page.locator('#deploy-note').inputValue() === '预发验收：验证订单分页与响应时间', '失败后保留部署说明')
  assert((await saved()).length === 3, '请求失败不创建虚假部署记录')
  await openScenario()
  await page.locator('#request-failure').uncheck()
  await closeScenario()
  await page.locator('form').evaluate(form => { form.requestSubmit(); form.requestSubmit() })
  await page.waitForURL(/\/deployments\/DEP-/)
  const successUrl = page.url()
  await visible(page.getByRole('heading', { name: '部署请求已提交，等待执行' }), '受理后显示等待执行，不提前报告成功')
  assert((await saved()).length === 4, '连续两次提交只创建一条记录')
  await page.reload()
  await visible(page.getByText('预发验收：验证订单分页与响应时间', { exact: true }), '刷新后保留部署记录和说明')
  await visible(page.getByRole('heading', { name: '部署完成，服务已更新' }), '模拟执行最终到达成功状态')
  await page.screenshot({ path: 'output/devops-deployment-success.png', fullPage: true })
  await page.getByRole('link', { name: '查看环境', exact: true }).click()
  assert((await page.locator('.environment-card').filter({ hasText: '预发环境' }).innerText()).includes('v1.8.0'), '成功部署更新目标环境显示版本')
  await go('/deployments')
  await page.getByRole('searchbox', { name: '搜索部署编号、版本或说明' }).fill('不存在的记录')
  await visible(page.getByRole('heading', { name: '没有符合条件的部署' }), '筛选无结果显示独立空状态')
  await page.getByRole('button', { name: '清除筛选' }).click()
  assert(await page.locator('tbody tr').count() === 4, '清除筛选恢复全部记录')
  await page.getByLabel('按部署状态筛选').selectOption('failed')
  assert(await page.locator('tbody tr').count() === 1, '状态筛选只显示失败记录')
  await go('/deploy/new')
  await page.locator('input[name="environment"][value="test"]').check()
  await page.locator('#deploy-note').fill('健康检查失败后保留的说明')
  await openScenario()
  await page.locator('#outcome').selectOption('failure')
  await closeScenario()
  await page.getByRole('button', { name: '确认并发起部署' }).click()
  await page.waitForURL(/\/deployments\/DEP-/)
  const failureUrl = page.url()
  await visible(page.getByRole('heading', { name: '健康检查未通过，部署失败' }), '健康检查失败停止流程并报告失败')
  await page.getByRole('link', { name: '重新部署', exact: true }).click()
  assert(await page.locator('input[value="test"]').isChecked() && await page.locator('#deploy-note').inputValue() === '健康检查失败后保留的说明', '重新部署保留目标环境和说明')
  await go('/environments')
  assert((await page.locator('.environment-card').filter({ hasText: '测试环境' }).innerText()).includes('v1.7.8'), '失败部署不会覆盖环境的可用版本')
  await go('/pipelines/2841')
  await openScenario()
  await page.getByRole('radio', { name: '检查失败', exact: true }).check()
  await closeScenario()
  assert(await page.getByRole('link', { name: '部署到预发', exact: true }).count() === 0, '检查失败时移除可操作部署入口')
  await visible(page.locator('.artifact-panel .compact-empty'), '检查失败时不伪装存在构建产物')
  await page.locator('.main-nav').getByRole('link', { name: '部署记录' }).click()
  await page.getByRole('link', { name: '发起部署', exact: true }).click()
  assert(await page.getByRole('button', { name: '确认并发起部署' }).isDisabled(), '从其他页面进入也无法绕过检查限制')
  await openScenario()
  await page.getByRole('radio', { name: '检查通过', exact: true }).check()
  await page.locator('#deploy-permission').uncheck()
  await closeScenario()
  assert(await page.getByRole('button', { name: '确认并发起部署' }).isDisabled(), '检查通过但无权限仍不能提交')
  await openScenario()
  await page.locator('#deploy-permission').check()
  await page.locator('#long-content').check()
  await closeScenario()
  await page.keyboard.press('Control+k')
  await page.getByRole('searchbox', { name: '搜索页面、部署编号或版本' }).fill('环境')
  await page.getByRole('dialog').getByRole('link', { name: /环境总览/ }).click()
  await visible(page.getByRole('heading', { name: '环境总览', exact: true }), '键盘全局搜索可以导航')
  const pages = ['/pipelines/2841', '/deploy/new', '/deployments', '/environments', '/design', new URL(failureUrl).hash.slice(1)]
  for (const width of [320, 390, 768, 1024, 1440]) {
    await page.setViewportSize({ width, height: width < 760 ? 844 : 1000 })
    await page.evaluate(() => { location.hash = '#/pipelines/2841' })
    await page.getByRole('heading', { name: /流水线详情/ }).waitFor()
    await page.evaluate(() => window.scrollTo(0, 500))
    const header = await page.locator('.topbar').boundingBox()
    assert(Math.abs(header.y) < 1 && header.x >= 0 && header.x + header.width <= width + 1, `${width}px 顶部导航滚动后仍固定且宽度正确`)
    await page.getByRole('button', { name: /搜索项目内容/ }).focus()
    assert((await page.getByRole('button', { name: /搜索项目内容/ }).boundingBox()).y >= 0, `${width}px 顶部搜索可聚焦且不被遮挡`)
    await page.evaluate(() => window.scrollTo(0, 0))
    for (const path of pages) {
      // 使用路由内跳转，保留长内容场景配置。
      await page.evaluate(path => { location.hash = `#${path}` }, path)
      await page.waitForFunction(path => location.hash === `#${path}` && document.querySelector('main h1'), path)
      await page.locator('main').evaluate(el => new Promise(resolve => requestAnimationFrame(() => requestAnimationFrame(resolve))))
      const sizes = await page.evaluate(() => ({ client: document.documentElement.clientWidth, scroll: document.documentElement.scrollWidth }))
      assert(sizes.scroll <= sizes.client + 1, `${width}px ${path} 无整页横向溢出`)
      assert(await page.locator('main h1').count() === 1, `${width}px ${path} 只有一个主标题`)
    }
    if (width === 390 || width === 1440) {
      await page.evaluate(() => { location.hash = '#/pipelines/2841' })
      await page.getByRole('heading', { name: /流水线详情/ }).waitFor()
      await page.screenshot({ path: `output/devops-pipeline-${width}.png`, fullPage: true })
      await page.evaluate(() => { location.hash = '#/deploy/new' })
      await page.getByRole('heading', { name: '部署确认', exact: true }).waitFor()
      await page.screenshot({ path: `output/devops-confirm-${width}.png`, fullPage: true })
    }
  }
  await page.setViewportSize({ width: 1440, height: 1000 })
  await go('/deployments')
  await openScenario()
  await page.getByRole('button', { name: '清空部署记录' }).click()
  await closeScenario()
  await visible(page.getByRole('heading', { name: '准备好你的第一次部署' }), '真正没有记录时提供首次部署入口')
  await page.goto(successUrl)
  await visible(page.getByRole('heading', { name: '没有找到这条部署记录' }), '已清空记录有明确的详情缺失状态')
  await go('/unknown')
  await visible(page.locator('main h1'), '未知路由有返回入口')
  await page.evaluate(() => localStorage.setItem('devops-demo-v1', '{broken'))
  await go('/pipelines/2841')
  await page.reload()
  await visible(page.locator('.storage-notice'), '本地记录损坏时恢复示例并说明原因')
  await page.reload()
  await visible(page.getByRole('link', { name: 'DevOps WORKSPACE' }), '项目名称统一为 DevOps')
  await page.screenshot({ path: 'output/devops-final-desktop.png', fullPage: true })
  assert(errors.length === 0, `浏览器无运行错误：${errors.join('; ')}`)
  return { passed: checks.length, checks, screenshots: ['output/devops-final-desktop.png', 'output/devops-pipeline-390.png', 'output/devops-confirm-390.png', 'output/devops-deployment-success.png'] }
}
